//! Generate the seven markers used by the compiled ICU4X collator provider.
use icu_locale::fallback::LocaleFallbacker;
use icu_provider_export::{
    baked_exporter::{BakedExporter, Options},
    prelude::*,
};
use icu_provider_source::{CollationRootHan, SourceDataProvider};
use sha2::{Digest, Sha256};
use std::{error::Error, fs, path::Path};

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = std::env::args_os().skip(1).collect();
    if args.len() != 3 {
        return Err("usage: collation-datagen ICU_EXPORT_ZIP CLDR_JSON_ZIP NEW_OUTPUT_DIR".into());
    }
    let out = Path::new(&args[2]);
    fs::create_dir(out)?;
    let source = SourceDataProvider::new_custom()
        .with_icuexport(Path::new(&args[0]))?
        .with_cldr(Path::new(&args[1]))?
        .with_collation_root_han(CollationRootHan::Unihan);
    let options = Options::default();
    let exporter = BakedExporter::new(out.join("data"), options)?;
    ExportDriver::new(
        [DataLocaleFamily::FULL],
        DeduplicationStrategy::Maximal.into(),
        LocaleFallbacker::try_new_unstable(&source)?,
    )
    .with_markers(icu_collator::provider::MARKERS.iter().copied())
    .export(&source, exporter)?;
    fs::write(
        out.join("lib.rs"),
        "// @generated by tools/collation-datagen. ICU 78.2 / CLDR JSON 48.0.0, Unihan.\n// Unicode License v3; see LICENSE.\n#![no_std]\ninclude!(\"data/mod.rs\");\n",
    )?;
    fs::write(
        out.join("Cargo.toml"),
        "# @generated by tools/collation-datagen\n[package]\nname = \"icu_collator_data\"\nversion = \"2.1.1\"\nedition = \"2021\"\nlicense = \"Unicode-3.0\"\npublish = false\n[lib]\npath = \"lib.rs\"\n",
    )?;
    fs::write(
        out.join("LICENSE"),
        format!(
            "{}\n\nCLDR JSON 48.0.0 license:\n{}",
            include_str!("../LICENSE.unicode"),
            include_str!("../LICENSE.cldr")
        ),
    )?;
    let mut files = Vec::new();
    for entry in fs::read_dir(out)? {
        let entry = entry?;
        if entry.file_type()?.is_dir() {
            for child in fs::read_dir(entry.path())? {
                files.push(child?.path());
            }
        } else {
            files.push(entry.path());
        }
    }
    files.sort();
    let mut hashes = String::new();
    for file in files {
        hashes.push_str(&format!(
            "{:x}  {}\n",
            Sha256::digest(fs::read(&file)?),
            file.strip_prefix(out)?.display()
        ));
    }
    fs::write(out.join("SHA256SUMS"), hashes)?;
    Ok(())
}
