// Run with the pinned Node: node --expose-internals tests/generate_node_io.mjs [--check]
// util.getSystemErrorMap is Node's libuv uv_err_name/uv_strerror table.
// libc supplies target errno numbers at compile time; never reuse Darwin numbers on Linux.
import {execFileSync} from 'node:child_process';
import {getSystemErrorMap} from 'node:util';
import {constants} from 'node:os';
import {createRequire} from 'node:module';
import {openSync,readFileSync,readdirSync,statSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {UVException}=require('internal/errors');
if(process.version!=='v22.22.0'||process.versions.uv!=='1.52.1')throw Error('Node v22.22.0 / libuv 1.52.1 required');
const all=[...getSystemErrorMap()].map(([uv,[code,description]])=>({uv,code,description})).sort((a,b)=>a.code.localeCompare(b.code,'en'));
// These libuv codes have no POSIX errno. Platform-only POSIX names are retained.
const entries=all.filter(e=>!e.code.startsWith('EAI_')&&!['UNKNOWN','EOF','ECHARSET'].includes(e.code));
const onlyLinux=new Set(['ENONET','EREMOTEIO','EUNATCH']);
const onlyDarwin=new Set(['EFTYPE']);
const guard=e=>onlyLinux.has(e.code)?'#[cfg(target_os = "linux")]':onlyDarwin.has(e.code)?'#[cfg(target_os = "macos")]':'#[cfg(any(target_os = "macos", target_os = "linux"))]';
const lines=['// Generated by tests/generate_node_io.mjs using Node v22.22.0 / libuv 1.52.1.', '// Do not edit errno names or descriptions by hand.', 'pub(super) const ERRORS: &[(i32, &str, &str)] = &['];
for(const e of entries)lines.push(`    ${guard(e)}`,`    (libc::${e.code}, ${JSON.stringify(e.code)}, ${JSON.stringify(e.description)}),`);
lines.push('];','');
// Real fs errors report through the C++ binding formatter, which appends a
// provided path verbatim, empty included; the JS `UVException` class used
// below truthiness-drops an empty path (`if (ctx.path)`). Measure the binding
// rule through real fs calls before recording it for the '' rows, so the
// goldens match what openSync/statSync/readdirSync actually print.
for(const [syscall,probe] of [['open',() => openSync('')],['stat',() => statSync('')],['scandir',() => readdirSync('')]]){
 try{probe();}catch(error){
  if(error?.code==='ENOENT'&&error.message.endsWith(` ${syscall} ''`))continue;
  throw Error('binding empty-path rule changed: '+error?.message);
 }
 throw Error('empty-path fs call unexpectedly succeeded');
}
const formatting=[];
for(const e of entries)for(const syscall of ['stat','open','read','fstat','scandir','realpath'])for(const path of [undefined,'',"/fixture/quote' and\nline"]){
 const error=new UVException({errno:e.uv,syscall,...(path===undefined?{}:{path})});
 const message=path===''?error.message+" ''":error.message;
 formatting.push({code:e.code,syscall,...(path===undefined?{}:{path}),message});
}
const fixture={node:process.version,uv:process.versions.uv,platform:process.platform,all,errno:constants.errno,formatting};
for(const [url,content] of [[new URL('../src/node_io/generated.rs',import.meta.url),execFileSync('rustfmt',['--edition','2024'],{input:lines.join('\n'),encoding:'utf8'})],[new URL('fixtures/node-io/errors.json',import.meta.url),JSON.stringify(fixture,null,2)+'\n']]){
 const path=fileURLToPath(url);
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==content)throw Error('Generated output differs: '+path);}else writeFileSync(path,content);
}
console.log(JSON.stringify({node:process.version,uv:process.versions.uv,libuvEntries:all.length,posixNames:entries.length,formatting:formatting.length,check:process.argv.includes('--check')}));
