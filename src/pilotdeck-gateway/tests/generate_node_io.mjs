// Run with the pinned Node: node --expose-internals tests/generate_node_io.mjs [--check]
// The table collection itself (libuv map, binding probes, UVException goldens,
// version gate) lives in node-io-tables.mjs, shared with the Linux verifier.
// libc supplies target errno numbers at compile time; never reuse Darwin numbers on Linux.
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {collectErrnoTables} from './node-io-tables.mjs';
const {document:fixture,entries}=collectErrnoTables();
const onlyLinux=new Set(['ENONET','EREMOTEIO','EUNATCH']);
const onlyDarwin=new Set(['EFTYPE']);
const guard=e=>onlyLinux.has(e.code)?'#[cfg(target_os = "linux")]':onlyDarwin.has(e.code)?'#[cfg(target_os = "macos")]':'#[cfg(any(target_os = "macos", target_os = "linux"))]';
const lines=['// Generated by tests/generate_node_io.mjs using Node v22.22.0 / libuv 1.52.1.', '// Do not edit errno names or descriptions by hand.', 'pub(super) const ERRORS: &[(i32, &str, &str)] = &['];
for(const e of entries)lines.push(`    ${guard(e)}`,`    (libc::${e.code}, ${JSON.stringify(e.code)}, ${JSON.stringify(e.description)}),`);
lines.push('];','');
for(const [url,content] of [[new URL('../src/node_io/generated.rs',import.meta.url),execFileSync('rustfmt',['--edition','2024'],{input:lines.join('\n'),encoding:'utf8'})],[new URL('fixtures/node-io/errors.json',import.meta.url),JSON.stringify(fixture,null,2)+'\n']]){
 const path=fileURLToPath(url);
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==content)throw Error('Generated output differs: '+path);}else writeFileSync(path,content);
}
console.log(JSON.stringify({node:process.version,uv:process.versions.uv,libuvEntries:fixture.all.length,posixNames:entries.length,formatting:fixture.formatting.length,check:process.argv.includes('--check')}));
