//! #969 each committed TS cell is covered by the byte-identical regeneration manifest.
#[allow(dead_code)]
#[path = "common/baseline.rs"]
mod baseline;

use sha2::{Digest, Sha256};
use std::path::Path;

fn check_cell(name: &str) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/live-e2e");
    let oracle: serde_json::Value = serde_json::from_slice(
        &std::fs::read(root.join("oracle.json")).expect("#969 read TS regeneration manifest"),
    )
    .expect("#969 decode TS regeneration manifest");
    let expected = oracle["expectedSha256"][name]
        .as_str()
        .expect("#969 every matrix cell must have a frozen digest");
    let actual = std::fs::read(root.join("expected").join(format!("{name}.json")))
        .expect("#969 read complete TS expected cell");
    assert_eq!(
        format!("{:x}", Sha256::digest(actual)),
        expected,
        "#969 {name}: expected file must match independently regenerated bytes"
    );
}

macro_rules! cell {
    ($test:ident, $name:literal) => {
        #[test]
        fn $test() {
            check_cell($name);
        }
    };
}
cell!(text_passthrough, "text-passthrough");
cell!(text_drop, "text-drop");
cell!(text_duplicate, "text-duplicate");
cell!(text_early_final, "text-early-final");
cell!(tool_passthrough, "tool-passthrough");
cell!(tool_drop, "tool-drop");
cell!(tool_duplicate, "tool-duplicate");
cell!(tool_early_final, "tool-early-final");
cell!(cancel_passthrough, "cancel-passthrough");
cell!(cancel_drop, "cancel-drop");
cell!(cancel_duplicate, "cancel-duplicate");
cell!(cancel_early_final, "cancel-early-final");

#[test]
#[ignore = "requires fixed PilotDeck baseline and Node v22.22.0"]
fn live_e2e_regenerates_identically() {
    for scenario in ["text", "tool", "cancel"] {
        for injection in ["passthrough", "drop", "duplicate", "early-final"] {
            check_cell(&format!("{scenario}-{injection}"));
        }
    }
    baseline::regenerates_identically("live-e2e");
}
