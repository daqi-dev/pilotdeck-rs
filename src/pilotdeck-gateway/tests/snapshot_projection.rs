fn oracle() -> JsValue {
    let path = format!("{FIXTURES}/oracle.json");
    let Ok(json) = fs::read_to_string(&path) else {
        panic!(
            "#888 oracle.json is missing; generate it first \
             (tests/fixtures/snapshot-projection/README.md):\n\
             PDRS_BASELINE=/absolute/path/to/PilotDeck node --import \
             \"$PDRS_BASELINE/node_modules/tsx/dist/loader.mjs\" \
             {FIXTURES}/generate.mts {FIXTURES}"
        );
    };
    for fixed in ["/tmp/pdrs-a66p4-", "/tmp/pdrs-"] {
        assert!(
            !json.contains(fixed),
            "#888 oracle.json keeps a fixed temporary path: {fixed}"
        );
    }
    let oracle = baseline::oracle(&json);
    assert!(
        text(field(&oracle, "node")).starts_with("v22."),
        "#888 oracle was generated by Node 22"
    );
    assert!(
        !text(field(&oracle, "v8")).is_empty(),
        "#888 v8 is recorded"
    );
    assert!(
        !text(field(&oracle, "locale")).is_empty(),
        "#888 locale is recorded"
    );
    assert!(
        text(field(&oracle, "sourceTreeSha256")).len() == 64,
        "#888 sourceTreeSha256 is a SHA-256"
    );
    assert!(
        number(field(&oracle, "sourceTreeFiles")) > 0.0,
        "#888 source tree file count is positive"
    );
    oracle
}

fn items(value: &JsValue) -> &[JsValue] {
    match value {
        JsValue::Array(items) => items,
        other => panic!("#888 expected an array, got {other:?}"),
    }
}
fn field<'a>(value: &'a JsValue, key: &str) -> &'a JsValue {
    value.get(key).unwrap_or(&UNDEFINED)
}
fn text(value: &JsValue) -> String {
    value
        .as_string()
        .unwrap_or_else(|| panic!("expected a string, got {value:?}"))
        .to_utf8()
        .expect("#888 UTF-8 fixture string")
}
fn number(value: &JsValue) -> f64 {
    value.as_number().expect("#888 fixture number")
}
fn decode(value: &JsValue) -> Vec<u8> {
    base64::engine::general_purpose::STANDARD
        .decode(text(value))
        .expect("#888 fixture base64")
}

struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let base = PathBuf::from("/tmp");
        fs::create_dir_all(&base).expect("#888 create scratch base");
        loop {
            let nanos = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("#888 system time after the epoch")
                .subsec_nanos();
            let token = u64::from(nanos)
                ^ (u64::from(std::process::id()) << 20)
                ^ (NEXT.fetch_add(1, Ordering::Relaxed) as u64).wrapping_mul(0x9e37_79b9);
            let token = format!("{token:06x}");
            let dir = base.join(format!("pdrs-a66p4t-{}", &token[token.len() - 6..]));
            match fs::create_dir(&dir) {
                Ok(()) => return Self(dir),
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("create scratch {}: {error}", dir.display()),
            }
        }
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn expand(input: &str, scratch: &Path) -> String {
    input.replace("<dir>", &scratch.to_string_lossy())
}
fn expand_value(value: &JsValue, scratch: &Path) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(expand(
            &String::from_utf16_lossy(value.units()),
            scratch,
        ))),
        JsValue::Array(values) => JsValue::Array(
            values
                .iter()
                .map(|value| expand_value(value, scratch))
                .collect(),
        ),
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), expand_value(value, scratch));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
fn mask(value: &JsValue, from: &str, to: &str) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(
            String::from_utf16_lossy(value.units()).replace(from, to),
        )),
        JsValue::Array(values) => {
            JsValue::Array(values.iter().map(|value| mask(value, from, to)).collect())
        }
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), mask(value, from, to));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
/// Mask a random mkdtemp suffix quoted in a Node error. The oracle records
/// `.../.pilotdeck-restore-<random>`; the native run draws its own six
/// `[A-Za-z0-9]` characters.
fn mask_restore_random(value: &JsValue) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(mask_restore_random_text(
            &String::from_utf16_lossy(value.units()),
        ))),
        JsValue::Array(values) => JsValue::Array(values.iter().map(mask_restore_random).collect()),
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), mask_restore_random(value));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
fn mask_restore_random_text(text: &str) -> String {
    const PREFIX: &str = ".pilotdeck-restore-";
    let mut output = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(index) = rest.find(PREFIX) {
        let (head, tail) = rest.split_at(index + PREFIX.len());
        output.push_str(head);
        let bytes = tail.as_bytes();
        let mut length = 0;
        while length < 6 && bytes.get(length).is_some_and(u8::is_ascii_alphanumeric) {
            length += 1;
        }
        if length == 6 && &tail[..6] != "XXXXXX" {
            output.push_str("<random>");
            rest = &tail[length..];
        } else if length == 6 {
            // The literal mkdtemp template is not a random name; leave it so
            // a hand-written/template path cannot masquerade as `<random>`.
            output.push_str(&tail[..6]);
            rest = &tail[length..];
        } else {
            output.push_str(tail);
            rest = "";
        }
    }
    output.push_str(rest);
    output
}

/// Materialize the recorded snapshot root. Manifest bytes were projected with
/// `<dir>` for the one hand-planted absolute objectKey; substitute the scratch
/// directory again before writing. Other files stay byte-exact.
fn materialize(scenario: &JsValue, scratch: &Path) {
    let storage = scratch.join("storage");
    fs::create_dir_all(&storage).expect("#888 create materialized storage");
    for row in items(field(scenario, "tree")) {
        let relative = text(field(row, "path"));
        let path = storage.join(&relative);
        let parent = path
            .parent()
            .expect("#888 tree row has a parent")
            .to_path_buf();
        fs::create_dir_all(&parent).expect("#888 create tree parent");
        match text(field(row, "kind")).as_str() {
            "dir" => fs::create_dir_all(&path).expect("#888 create tree directory"),
            "symlink" => {
                let _ = fs::remove_file(&path);
                symlink(text(field(row, "target")), &path).expect("#888 create tree symlink");
            }
            "file" => {
                let mut bytes = decode(field(row, "b64"));
                if relative.ends_with("manifest.json") {
                    bytes = replace_bytes(&bytes, b"<dir>", scratch.as_os_str().as_bytes());
                }
                fs::write(&path, bytes).expect("#888 write tree file");
            }
            kind => panic!("unknown tree kind {kind}"),
        }
    }
    if let Some(absolute) = field(scenario, "absoluteFile").as_object() {
        let path = PathBuf::from(expand(
            &text(absolute.get("path").expect("#888 absoluteFile.path")),
            scratch,
        ));
        fs::create_dir_all(path.parent().expect("#888 path has a parent"))
            .expect("#888 create file parent");
        fs::write(
            &path,
            decode(absolute.get("b64").expect("#888 absoluteFile.b64")),
        )
        .expect("#888 write absolute file");
    }
    for project in items(field(scenario, "projects")) {
        // A `missing` project is registry-only: the real TS general workspace
        // resolves without a stat, and the scenario deliberately removed it so
        // mkdtemp fails. Do not recreate it during materialization.
        if field(project, "missing").as_bool() == Some(true) {
            continue;
        }
        fs::create_dir_all(expand(&text(field(project, "key")), scratch))
            .expect("#888 create project directory");
    }
    // `gateway-native` replays the production project registry: rebuild the
    // pilot home, the `.cwd` markers and the marker-to-file conflict from the
    // oracle instead of injecting TestResolver's table.
    if let Some(native) = field(scenario, "native").as_object() {
        let home = PathBuf::from(expand(
            &text(native.get("pilotHome").expect("#888 native.pilotHome")),
            scratch,
        ));
        fs::create_dir_all(&home).expect("#888 create native pilot home");
        for project in items(native.get("projects").expect("#888 native.projects")) {
            let id = text(field(project, "id"));
            let dir = home.join("projects").join(&id);
            fs::create_dir_all(&dir).expect("#888 create native registry directory");
            if let Some(marker) = field(project, "marker").as_string() {
                fs::write(
                    dir.join(".cwd"),
                    expand(&String::from_utf16_lossy(marker.units()), scratch),
                )
                .expect("#888 write native marker");
            }
        }
        for file in items(native.get("files").expect("#888 native.files")) {
            let path = PathBuf::from(expand(&text(field(file, "path")), scratch));
            fs::create_dir_all(path.parent().expect("#888 path has a parent"))
                .expect("#888 create file parent");
            fs::write(path, text(field(file, "content"))).expect("#888 write native file");
        }
        for link in items(native.get("symlinks").expect("#888 native.symlinks")) {
            let path = PathBuf::from(expand(&text(field(link, "path")), scratch));
            fs::create_dir_all(path.parent().expect("#888 link path has a parent"))
                .expect("#888 create native link parent");
            symlink(expand(&text(field(link, "target")), scratch), &path)
                .expect("#888 create native symlink");
        }
    }
}
fn replace_bytes(bytes: &[u8], needle: &[u8], replacement: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index..].starts_with(needle) {
            out.extend_from_slice(replacement);
            index += needle.len();
        } else {
            out.push(bytes[index]);
            index += 1;
        }
    }
    out
}

struct TestResolver {
    projects: Vec<(String, String)>,
}
impl SnapshotProjectResolver for TestResolver {
    fn resolve_project_key(&self, project_key: &[u16]) -> Result<String, SnapshotProjectionError> {
        // JS `===`, i.e. code-unit equality: a lone surrogate must not be
        // replacement-decoded before matching a registry path.
        let normalized = normalize_units(project_key);
        self.projects
            .iter()
            .find(|(key, _)| normalize_units(&key.encode_utf16().collect::<Vec<_>>()) == normalized)
            .map(|(key, _)| key.clone())
            .ok_or_else(|| SnapshotProjectionError::unknown_project_key(project_key))
    }
    fn workspace_id(&self, project_key: &str) -> String {
        let normalized = normalize(project_key);
        self.projects
            .iter()
            .find(|(key, _)| normalize(key) == normalized)
            .map(|(_, workspace)| workspace.clone())
            .unwrap_or_default()
    }
}
/// Either the injected table (projection scenarios) or the production
/// metadata resolver (`gateway-native`); both feed one `SnapshotProjection`.
enum ReplayResolver {
    Test(TestResolver),
    Native(SnapshotProjects),
}
impl SnapshotProjectResolver for ReplayResolver {
    fn resolve_project_key(&self, project_key: &[u16]) -> Result<String, SnapshotProjectionError> {
        match self {
            Self::Test(resolver) => resolver.resolve_project_key(project_key),
            Self::Native(resolver) => resolver.resolve_project_key(project_key),
        }
    }
    fn workspace_id(&self, project_key: &str) -> String {
        match self {
            Self::Test(resolver) => resolver.workspace_id(project_key),
            Self::Native(resolver) => resolver.workspace_id(project_key),
        }
    }
}

/// `Projection` keeps the original six scenarios; `Gateway` adds the
/// InProcessGateway method validators for `gateway-native`.
enum Replay {
    Projection(SnapshotProjection<ReplayResolver>),
    Gateway(SnapshotGateway<ReplayResolver>),
}
impl Replay {
    fn call(&self, op: &str, input: &JsValue) -> Result<JsValue, SnapshotProjectionError> {
        match self {
            Self::Projection(projection) => match op {
                "snapshotList" => projection.list(input),
                "snapshotGet" => projection.get(input),
                "snapshotRestore" => projection.restore(input),
                other => panic!("#888 unknown replay operation {other}"),
            },
            Self::Gateway(gateway) => match op {
                "snapshotList" => gateway.list(input),
                "snapshotGet" => gateway.get(input),
                "snapshotRestore" => gateway.restore(input),
                other => panic!("#888 unknown replay operation {other}"),
            },
        }
    }
}

fn normalize(path: &str) -> String {
    let trimmed = path.trim_end_matches('/');
    if trimmed.is_empty() {
        "/".into()
    } else {
        trimmed.into()
    }
}
/// The registry comparison on raw units: trim trailing `/` without decoding.
fn normalize_units(path: &[u16]) -> Vec<u16> {
    let mut end = path.len();
    while end > 0 && path[end - 1] == u16::from(b'/') {
        end -= 1;
    }
    if end == 0 {
        vec![u16::from(b'/')]
    } else {
        path[..end].to_vec()
    }
}

/// Node `path.join(target, name)` lexical normalization. `Path::join` alone
/// preserves `..`, which would make a `link/..` target compare against the
/// symlink-resolved spelling Node never returns.
fn lexical_join(base: &str, name: &str) -> String {
    let mut joined = PathBuf::new();
    for component in Path::new(base).join(name).components() {
        match component {
            Component::ParentDir => {
                joined.pop();
            }
            Component::CurDir => {}
            component => joined.push(component.as_os_str()),
        }
    }
    joined.to_string_lossy().into_owned()
}

fn restore_dirs(project: &Path) -> Vec<String> {
    fs::read_dir(project)
        .map(|entries| {
            entries
                .flatten()
                .filter_map(|entry| {
                    entry
                        .file_name()
                        .to_str()
                        .filter(|name| name.starts_with(".pilotdeck-restore-"))
                        .map(str::to_owned)
                })
                .collect()
        })
        .unwrap_or_default()
}

fn record_tree(root: &Path) -> Vec<JsValue> {
    let mut rows = Vec::new();
    walk(root, root, &mut rows);
    rows.sort_by_key(|row| text(field(row, "path")));
    rows
}
fn walk(root: &Path, directory: &Path, rows: &mut Vec<JsValue>) {
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let relative = path
            .strip_prefix(root)
            .expect("#888 recorded path stays under the scratch root")
            .to_string_lossy()
            .into_owned();
        let Ok(info) = fs::symlink_metadata(&path) else {
            continue;
        };
        let mut row = JsObject::new();
        row.insert("path".into(), relative.as_str().into());
        if info.is_dir() {
            row.insert("kind".into(), "dir".into());
            rows.push(JsValue::Object(row));
            walk(root, &path, rows);
        } else if info.file_type().is_symlink() {
            row.insert("kind".into(), "symlink".into());
            row.insert(
                "target".into(),
                fs::read_link(&path)
                    .expect("#888 read recorded symlink")
                    .to_string_lossy()
                    .as_ref()
                    .into(),
            );
            rows.push(JsValue::Object(row));
        } else {
            row.insert("kind".into(), "file".into());
            row.insert(
                "b64".into(),
                base64::engine::general_purpose::STANDARD
                    .encode(fs::read(&path).expect("#888 read recorded file"))
                    .as_str()
                    .into(),
            );
            rows.push(JsValue::Object(row));
        }
    }
}

#[test]
fn scenarios_match_real_ts_projection() {
    let oracle = oracle();
    let scenarios = items(field(&oracle, "scenarios"));
    assert_eq!(
        scenarios.len(),
        EXPECTED.len(),
        "#888 snapshot-projection corpus is pinned"
    );
    assert_eq!(
        scenarios
            .iter()
            .map(|scenario| text(field(scenario, "name")))
            .collect::<Vec<_>>(),
        EXPECTED
            .iter()
            .map(|(name, _, _)| (*name).to_owned())
            .collect::<Vec<_>>()
    );
    assert_eq!(
        scenarios
            .iter()
            .map(|scenario| items(field(scenario, "operations")).len())
            .sum::<usize>(),
        115,
        "#888 115 snapshot operations are replayed"
    );

    for (scenario, (name, expected_ops, expected_tree)) in scenarios.iter().zip(EXPECTED) {
        assert_eq!(&text(field(scenario, "name")), name);
        assert_eq!(
            items(field(scenario, "operations")).len(),
            *expected_ops,
            "#888 {name}: operation count"
        );
        assert_eq!(
            items(field(scenario, "tree")).len(),
            *expected_tree,
            "#888 {name}: materialized tree count"
        );

        let scratch = Scratch::new();
        materialize(scenario, &scratch.0);
        let projects: Vec<(String, String)> = items(field(scenario, "projects"))
            .iter()
            .map(|project| {
                (
                    expand(&text(field(project, "key")), &scratch.0),
                    text(field(project, "workspaceId")),
                )
            })
            .collect();
        let resolver = if let Some(native) = field(scenario, "native").as_object() {
            ReplayResolver::Native(SnapshotProjects::new(
                expand(
                    &text(native.get("pilotHome").expect("#888 native.pilotHome")),
                    &scratch.0,
                ),
                expand(
                    &text(native.get("cwd").expect("#888 native.cwd")),
                    &scratch.0,
                ),
            ))
        } else {
            ReplayResolver::Test(TestResolver {
                projects: projects.clone(),
            })
        };
        let provider = if field(scenario, "snapshotRoot").as_string().is_some() {
            let root = expand(&text(field(scenario, "snapshotRoot")), &scratch.0);
            Some(create_workspace_snapshot_provider(
                WorkspaceSnapshotConfig {
                    root: root.clone(),
                    snapshot_root: root,
                },
            ))
        } else {
            None
        };
        let projection = SnapshotProjection::new(
            provider,
            resolver,
            expand(&text(field(scenario, "fallbackProjectRoot")), &scratch.0),
        );
        let replay = if field(scenario, "gateway").as_bool() == Some(true) {
            Replay::Gateway(SnapshotGateway::from_projection(projection))
        } else {
            Replay::Projection(projection)
        };

        for (index, operation) in items(field(scenario, "operations")).iter().enumerate() {
            replay_operation(&replay, &scratch.0, scenario, operation, index);
        }
    }
}

fn nullish(value: &JsValue) -> bool {
    matches!(value, JsValue::Undefined | JsValue::Null)
}

fn replay_operation(
    replay: &Replay,
    scratch: &Path,
    scenario: &JsValue,
    operation: &JsValue,
    index: usize,
) {
    let name = text(field(scenario, "name"));
    let op = text(field(operation, "op"));
    let params_mode = field(operation, "params")
        .as_string()
        .map(|mode| mode.to_utf8().expect("#888 params mode is UTF-8"));
    let raw_input = match params_mode.as_deref() {
        Some("undefined") => JsValue::Undefined,
        Some("null") => JsValue::Null,
        Some(other) => panic!("#888 unknown params mode {other}"),
        None => expand_value(field(operation, "input"), scratch),
    };
    let target_project = if params_mode.is_none() && op == "snapshotRestore" {
        let target = field(&raw_input, "targetProjectKey");
        if nullish(target) {
            field(&raw_input, "projectKey")
                .as_string()
                .map(|key| expand(&text(&JsValue::String(key.clone())), scratch))
        } else {
            target
                .as_string()
                .map(|key| text(&JsValue::String(key.clone())))
        }
    } else {
        None
    };
    let before = target_project
        .as_deref()
        .map(|target| restore_dirs(Path::new(target)))
        .unwrap_or_default();
    let actual = replay.call(&op, &raw_input);
    // P1-1: a raw marker whose lexical resolution is the General workspace
    // but whose raw `stat` fails must not own the storage id. The dedicated
    // assertion runs before the generic value comparison so the negative
    // control sees this message instead of an incidental mismatch elsewhere.
    if name.starts_with("storage-id-") && op == "snapshotList" {
        let value = actual
            .as_ref()
            .unwrap_or_else(|error| panic!("#888 {name}: raw marker list failed: {error}"));
        let listed = match value.get("items") {
            Some(JsValue::Array(items)) => items,
            other => panic!("#888 {name}: raw marker list has no items array: {other:?}"),
        };
        assert_eq!(
            listed.len(),
            1,
            "#888 {name}: raw marker existence check keeps the General workspace id"
        );
        assert_eq!(
            listed[0]
                .get("workspaceId")
                .and_then(|value| value.as_string())
                .and_then(|value| value.to_utf8().ok())
                .as_deref(),
            Some("p-general"),
            "#888 {name}: raw marker existence check keeps the General workspace id"
        );
    }
    let after = target_project
        .as_deref()
        .map(|target| restore_dirs(Path::new(target)))
        .unwrap_or_default();
    let created: Vec<String> = after
        .into_iter()
        .filter(|name| !before.contains(name))
        .collect();
    let expected = field(operation, "outcome");
    let expected_restore_dir = matches!(field(operation, "restoreDir"), JsValue::Bool(true));
    assert_eq!(
        created.len(),
        usize::from(expected_restore_dir),
        "#888 {name} op #{index} ({op}): restore directory count"
    );
    let restore_dir = created
        .first()
        .zip(target_project.as_deref())
        .map(|(name, target)| lexical_join(target, name));
    // #293 registered divergence A6.6-SNAPSHOT-OBJECTKEY-001: the oracle's
    // "escape" snapshot pins TS restoring objectKeys outside the snapshot
    // root (`../outside.txt`, absolute paths; Node v22.22.0 probe
    // `_tmp/20261026-issue-293/probe-a-objectkey.out`). Rust refuses the
    // restore instead of copying root-external content into the target
    // workspace, so this operation's oracle outcome is replaced by the
    // divergence assertion below. The dedicated branch runs before the
    // generic comparison so a negative control sees this message.
    if name == "projection"
        && op == "snapshotRestore"
        && field(&raw_input, "snapshotId")
            .as_string()
            .is_some_and(|id| id.equals_str("escape"))
    {
        let error = actual.err().unwrap_or_else(|| {
            panic!("#293 {name} op #{index} ({op}): objectKey escape restore must be refused")
        });
        let value = error.as_json();
        assert_eq!(
            text(field(&value, "name")),
            "Error",
            "#293 {name} op #{index} ({op}): objectKey escape refusal name"
        );
        assert_eq!(
            text(field(&value, "message")),
            "Snapshot object key escapes the snapshot root.",
            "#293 {name} op #{index} ({op}): objectKey escape refusal message"
        );
        assert!(
            field(&value, "code").is_undefined(),
            "#293 {name} op #{index} ({op}): objectKey escape refusal carries no code"
        );
        if let Some(dir) = restore_dir.as_deref() {
            assert_eq!(
                mode(dir),
                0o700,
                "#293 {name} op #{index}: refused restore keeps the 0700 mkdtemp directory"
            );
            assert!(
                record_tree(Path::new(dir)).is_empty(),
                "#293 {name} op #{index}: refused restore writes nothing into the target"
            );
        }
        return;
    }

    // A successful restore must return the directory this call just created,
    // not a directory observed from an earlier operation. Node's `path.join`
    // normalizes the requested target lexically (`a/../b`), so compare against
    // that spelling before masking either path. Only then may the returned key
    // participate in masking/tree comparison.
    if let (Ok(value), Some(created_dir)) = (&actual, &restore_dir)
        && op == "snapshotRestore"
    {
        let workspace_key = value
            .get("workspaceKey")
            .and_then(|key| key.as_string())
            .and_then(|key| key.to_utf8().ok());
        assert_eq!(
            workspace_key.as_deref(),
            Some(created_dir.as_str()),
            "#888 {name} op #{index} ({op}): returned workspaceKey equals the newly created restore directory"
        );
    }

    match actual {
        Ok(value) => {
            let value = restore_dir
                .as_deref()
                .map_or(value.clone(), |dir| mask(&value, dir, "<restore>"));
            let value = mask(&value, &scratch.to_string_lossy(), "<dir>");
            let expected_value = expected.get("ok").unwrap_or_else(|| {
                panic!("#888 {name} op #{index} ({op}): expected an error, got {value:?}")
            });
            assert_eq!(
                value, *expected_value,
                "#888 {name} op #{index} ({op}): value mismatch"
            );
            if let Some(dir) = &restore_dir {
                assert_eq!(
                    mode(dir),
                    0o700,
                    "#888 {name} op #{index}: mkdtemp directory mode"
                );
                let tree = JsValue::Array(record_tree(Path::new(dir)));
                assert_eq!(
                    tree,
                    *field(operation, "targetTree"),
                    "#888 {name} op #{index}: restore tree"
                );
            }
        }
        Err(error) => {
            assert!(
                expected.get("ok").is_none(),
                "#888 {name} op #{index} ({op}): expected success, got {error}"
            );
            let value = error.as_json();
            let value = restore_dir
                .as_deref()
                .map_or(value.clone(), |dir| mask(&value, dir, "<restore>"));
            let value = mask(&value, &scratch.to_string_lossy(), "<dir>");
            let value = mask_restore_random(&value);
            assert_eq!(
                value,
                *field(expected, "error"),
                "#888 {name} op #{index} ({op}): error mismatch"
            );
            // A failed restore can still leave a partially written tree (for
            // example, the first entry succeeds and a later entry is unsafe).
            // The recorder captures `targetTree` for both outcomes, so compare
            // it and the 0700 guarantee on the failure path too; otherwise an
            // implementation could leave extra files while returning the same
            // error.
            if let Some(dir) = &restore_dir {
                assert_eq!(
                    mode(dir),
                    0o700,
                    "#888 {name} op #{index}: failed mkdtemp directory mode"
                );
                let tree = JsValue::Array(record_tree(Path::new(dir)));
                assert_eq!(
                    tree,
                    *field(operation, "targetTree"),
                    "#888 {name} op #{index}: failed restore tree"
                );
            }
        }
    }
}

