fn oracle() -> JsValue {
    let path = format!("{FIXTURES}/oracle.json");
    let Ok(json) = fs::read_to_string(&path) else {
        panic!(
            "oracle.json is missing; generate it first \
             (tests/fixtures/snapshot-projection/README.md):\n\
             PDRS_BASELINE=/absolute/path/to/PilotDeck node --import \
             \"$PDRS_BASELINE/node_modules/tsx/dist/loader.mjs\" \
             {FIXTURES}/generate.mts {FIXTURES}"
        );
    };
    for fixed in ["/tmp/pdrs-a66p4-", "/tmp/pdrs-"] {
        assert!(
            !json.contains(fixed),
            "oracle.json keeps a fixed temporary path: {fixed}"
        );
    }
    let oracle = baseline::oracle(&json);
    assert!(
        text(field(&oracle, "node")).starts_with("v22."),
        "oracle was generated by Node 22"
    );
    assert!(!text(field(&oracle, "v8")).is_empty());
    assert!(!text(field(&oracle, "locale")).is_empty());
    assert!(
        text(field(&oracle, "sourceTreeSha256")).len() == 64,
        "sourceTreeSha256 is a SHA-256"
    );
    assert!(number(field(&oracle, "sourceTreeFiles")) > 0.0);
    oracle
}

fn items(value: &JsValue) -> &[JsValue] {
    match value {
        JsValue::Array(items) => items,
        other => panic!("expected an array, got {other:?}"),
    }
}
fn field<'a>(value: &'a JsValue, key: &str) -> &'a JsValue {
    value.get(key).unwrap_or(&UNDEFINED)
}
fn text(value: &JsValue) -> String {
    value
        .as_string()
        .unwrap_or_else(|| panic!("expected a string, got {value:?}"))
        .to_utf8()
        .expect("UTF-8 fixture string")
}
fn number(value: &JsValue) -> f64 {
    value.as_number().expect("fixture number")
}
fn decode(value: &JsValue) -> Vec<u8> {
    base64::engine::general_purpose::STANDARD
        .decode(text(value))
        .expect("fixture base64")
}

struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let base = PathBuf::from("/tmp");
        fs::create_dir_all(&base).unwrap();
        loop {
            let nanos = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .subsec_nanos();
            let token = u64::from(nanos)
                ^ (u64::from(std::process::id()) << 20)
                ^ (NEXT.fetch_add(1, Ordering::Relaxed) as u64).wrapping_mul(0x9e37_79b9);
            let token = format!("{token:06x}");
            let dir = base.join(format!("pdrs-a66p4t-{}", &token[token.len() - 6..]));
            match fs::create_dir(&dir) {
                Ok(()) => return Self(dir),
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("create scratch {}: {error}", dir.display()),
            }
        }
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn expand(input: &str, scratch: &Path) -> String {
    input.replace("<dir>", &scratch.to_string_lossy())
}
fn expand_value(value: &JsValue, scratch: &Path) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(expand(
            &String::from_utf16_lossy(value.units()),
            scratch,
        ))),
        JsValue::Array(values) => JsValue::Array(
            values
                .iter()
                .map(|value| expand_value(value, scratch))
                .collect(),
        ),
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), expand_value(value, scratch));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
fn mask(value: &JsValue, from: &str, to: &str) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(
            String::from_utf16_lossy(value.units()).replace(from, to),
        )),
        JsValue::Array(values) => {
            JsValue::Array(values.iter().map(|value| mask(value, from, to)).collect())
        }
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), mask(value, from, to));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
/// Mask a random mkdtemp suffix quoted in a Node error. The oracle records
/// `.../.pilotdeck-restore-<random>`; the native run draws its own six
/// `[A-Za-z0-9]` characters.
fn mask_restore_random(value: &JsValue) -> JsValue {
    match value {
        JsValue::String(value) => JsValue::String(JsString::from(mask_restore_random_text(
            &String::from_utf16_lossy(value.units()),
        ))),
        JsValue::Array(values) => JsValue::Array(values.iter().map(mask_restore_random).collect()),
        JsValue::Object(object) => {
            let mut result = JsObject::new();
            for (key, value) in object.entries() {
                result.insert(key.clone(), mask_restore_random(value));
            }
            JsValue::Object(result)
        }
        other => other.clone(),
    }
}
fn mask_restore_random_text(text: &str) -> String {
    const PREFIX: &str = ".pilotdeck-restore-";
    let mut output = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(index) = rest.find(PREFIX) {
        let (head, tail) = rest.split_at(index + PREFIX.len());
        output.push_str(head);
        let bytes = tail.as_bytes();
        let mut length = 0;
        while length < 6 && bytes.get(length).is_some_and(u8::is_ascii_alphanumeric) {
            length += 1;
        }
        if length == 6 && &tail[..6] != "XXXXXX" {
            output.push_str("<random>");
            rest = &tail[length..];
        } else if length == 6 {
            // The literal mkdtemp template is not a random name; leave it so
            // a hand-written/template path cannot masquerade as `<random>`.
            output.push_str(&tail[..6]);
            rest = &tail[length..];
        } else {
            output.push_str(tail);
            rest = "";
        }
    }
    output.push_str(rest);
    output
}

/// Materialize the recorded snapshot root. Manifest bytes were projected with
/// `<dir>` for the one hand-planted absolute objectKey; substitute the scratch
/// directory again before writing. Other files stay byte-exact.
fn materialize(scenario: &JsValue, scratch: &Path) {
    let storage = scratch.join("storage");
    fs::create_dir_all(&storage).unwrap();
    for row in items(field(scenario, "tree")) {
        let relative = text(field(row, "path"));
        let path = storage.join(&relative);
        let parent = path.parent().expect("tree row has a parent").to_path_buf();
        fs::create_dir_all(&parent).unwrap();
        match text(field(row, "kind")).as_str() {
            "dir" => fs::create_dir_all(&path).unwrap(),
            "symlink" => {
                let _ = fs::remove_file(&path);
                symlink(text(field(row, "target")), &path).unwrap();
            }
            "file" => {
                let mut bytes = decode(field(row, "b64"));
                if relative.ends_with("manifest.json") {
                    bytes = replace_bytes(&bytes, b"<dir>", scratch.as_os_str().as_bytes());
                }
                fs::write(&path, bytes).unwrap();
            }
            kind => panic!("unknown tree kind {kind}"),
        }
    }
    if let Some(absolute) = field(scenario, "absoluteFile").as_object() {
        let path = PathBuf::from(expand(
            &text(absolute.get("path").expect("absoluteFile.path")),
            scratch,
        ));
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(
            &path,
            decode(absolute.get("b64").expect("absoluteFile.b64")),
        )
        .unwrap();
    }
    for project in items(field(scenario, "projects")) {
        // A `missing` project is registry-only: the real TS general workspace
        // resolves without a stat, and the scenario deliberately removed it so
        // mkdtemp fails. Do not recreate it during materialization.
        if field(project, "missing").as_bool() == Some(true) {
            continue;
        }
        fs::create_dir_all(expand(&text(field(project, "key")), scratch)).unwrap();
    }
}
fn replace_bytes(bytes: &[u8], needle: &[u8], replacement: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index..].starts_with(needle) {
            out.extend_from_slice(replacement);
            index += needle.len();
        } else {
            out.push(bytes[index]);
            index += 1;
        }
    }
    out
}

struct TestResolver {
    projects: Vec<(String, String)>,
}
impl SnapshotProjectResolver for TestResolver {
    fn resolve_project_key(&self, project_key: &[u16]) -> Result<String, SnapshotProjectionError> {
        // JS `===`, i.e. code-unit equality: a lone surrogate must not be
        // replacement-decoded before matching a registry path.
        let normalized = normalize_units(project_key);
        self.projects
            .iter()
            .find(|(key, _)| normalize_units(&key.encode_utf16().collect::<Vec<_>>()) == normalized)
            .map(|(key, _)| key.clone())
            .ok_or_else(|| SnapshotProjectionError::unknown_project_key(project_key))
    }
    fn workspace_id(&self, project_key: &str) -> String {
        let normalized = normalize(project_key);
        self.projects
            .iter()
            .find(|(key, _)| normalize(key) == normalized)
            .map(|(_, workspace)| workspace.clone())
            .unwrap_or_default()
    }
}
fn normalize(path: &str) -> String {
    let trimmed = path.trim_end_matches('/');
    if trimmed.is_empty() {
        "/".into()
    } else {
        trimmed.into()
    }
}
/// The registry comparison on raw units: trim trailing `/` without decoding.
fn normalize_units(path: &[u16]) -> Vec<u16> {
    let mut end = path.len();
    while end > 0 && path[end - 1] == u16::from(b'/') {
        end -= 1;
    }
    if end == 0 {
        vec![u16::from(b'/')]
    } else {
        path[..end].to_vec()
    }
}

fn restore_dirs(project: &Path) -> Vec<String> {
    fs::read_dir(project)
        .map(|entries| {
            entries
                .flatten()
                .filter_map(|entry| {
                    entry
                        .file_name()
                        .to_str()
                        .filter(|name| name.starts_with(".pilotdeck-restore-"))
                        .map(str::to_owned)
                })
                .collect()
        })
        .unwrap_or_default()
}

fn record_tree(root: &Path) -> Vec<JsValue> {
    let mut rows = Vec::new();
    walk(root, root, &mut rows);
    rows.sort_by_key(|row| text(field(row, "path")));
    rows
}
fn walk(root: &Path, directory: &Path, rows: &mut Vec<JsValue>) {
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let relative = path
            .strip_prefix(root)
            .unwrap()
            .to_string_lossy()
            .into_owned();
        let Ok(info) = fs::symlink_metadata(&path) else {
            continue;
        };
        let mut row = JsObject::new();
        row.insert("path".into(), relative.as_str().into());
        if info.is_dir() {
            row.insert("kind".into(), "dir".into());
            rows.push(JsValue::Object(row));
            walk(root, &path, rows);
        } else if info.file_type().is_symlink() {
            row.insert("kind".into(), "symlink".into());
            row.insert(
                "target".into(),
                fs::read_link(&path)
                    .unwrap()
                    .to_string_lossy()
                    .as_ref()
                    .into(),
            );
            rows.push(JsValue::Object(row));
        } else {
            row.insert("kind".into(), "file".into());
            row.insert(
                "b64".into(),
                base64::engine::general_purpose::STANDARD
                    .encode(fs::read(&path).unwrap())
                    .as_str()
                    .into(),
            );
            rows.push(JsValue::Object(row));
        }
    }
}

#[test]
fn scenarios_match_real_ts_projection() {
    let oracle = oracle();
    let scenarios = items(field(&oracle, "scenarios"));
    assert_eq!(
        scenarios.len(),
        EXPECTED.len(),
        "snapshot-projection corpus is pinned"
    );
    assert_eq!(
        scenarios
            .iter()
            .map(|scenario| text(field(scenario, "name")))
            .collect::<Vec<_>>(),
        EXPECTED
            .iter()
            .map(|(name, _, _)| (*name).to_owned())
            .collect::<Vec<_>>()
    );
    assert_eq!(
        scenarios
            .iter()
            .map(|scenario| items(field(scenario, "operations")).len())
            .sum::<usize>(),
        55,
        "55 projection operations are replayed"
    );

    for (scenario, (name, expected_ops, expected_tree)) in scenarios.iter().zip(EXPECTED) {
        assert_eq!(&text(field(scenario, "name")), name);
        assert_eq!(
            items(field(scenario, "operations")).len(),
            *expected_ops,
            "{name}: operation count"
        );
        assert_eq!(
            items(field(scenario, "tree")).len(),
            *expected_tree,
            "{name}: materialized tree count"
        );

        let scratch = Scratch::new();
        materialize(scenario, &scratch.0);
        let projects: Vec<(String, String)> = items(field(scenario, "projects"))
            .iter()
            .map(|project| {
                (
                    expand(&text(field(project, "key")), &scratch.0),
                    text(field(project, "workspaceId")),
                )
            })
            .collect();
        let resolver = TestResolver {
            projects: projects.clone(),
        };
        let provider = if field(scenario, "snapshotRoot").as_string().is_some() {
            let root = expand(&text(field(scenario, "snapshotRoot")), &scratch.0);
            Some(create_workspace_snapshot_provider(
                WorkspaceSnapshotConfig {
                    root: root.clone(),
                    snapshot_root: root,
                },
            ))
        } else {
            None
        };
        let projection = SnapshotProjection::new(
            provider,
            resolver,
            expand(&text(field(scenario, "fallbackProjectRoot")), &scratch.0),
        );

        for (index, operation) in items(field(scenario, "operations")).iter().enumerate() {
            replay_operation(&projection, &scratch.0, scenario, operation, index);
        }
    }
}

fn replay_operation(
    projection: &SnapshotProjection<TestResolver>,
    scratch: &Path,
    scenario: &JsValue,
    operation: &JsValue,
    index: usize,
) {
    let name = text(field(scenario, "name"));
    let op = text(field(operation, "op"));
    let raw_input = expand_value(field(operation, "input"), scratch);
    let target = field(&raw_input, "targetProjectKey");
    let target_project = if target.is_undefined() {
        expand(&text(field(&raw_input, "projectKey")), scratch)
    } else {
        text(target)
    };
    let before = restore_dirs(Path::new(&target_project));
    let actual = match op.as_str() {
        "snapshotList" => projection.list(&raw_input),
        "snapshotGet" => projection.get(&raw_input),
        "snapshotRestore" => projection.restore(&raw_input),
        other => panic!("{name} op #{index}: unknown operation {other}"),
    };
    let after = restore_dirs(Path::new(&target_project));
    let created: Vec<String> = after
        .into_iter()
        .filter(|name| !before.contains(name))
        .collect();
    let expected = field(operation, "outcome");
    let expected_restore_dir = matches!(field(operation, "restoreDir"), JsValue::Bool(true));
    assert_eq!(
        created.len(),
        usize::from(expected_restore_dir),
        "{name} op #{index} ({op}): restore directory count"
    );
    let restore_dir = created.first().map(|name| {
        Path::new(&target_project)
            .join(name)
            .to_string_lossy()
            .into_owned()
    });

    match actual {
        Ok(value) => {
            let value = restore_dir
                .as_deref()
                .map_or(value.clone(), |dir| mask(&value, dir, "<restore>"));
            let value = mask(&value, &scratch.to_string_lossy(), "<dir>");
            let expected_value = expected.get("ok").unwrap_or_else(|| {
                panic!("{name} op #{index} ({op}): expected an error, got {value:?}")
            });
            assert_eq!(
                value, *expected_value,
                "{name} op #{index} ({op}): value mismatch"
            );
            if let Some(dir) = &restore_dir {
                assert_eq!(
                    mode(dir),
                    0o700,
                    "{name} op #{index}: mkdtemp directory mode"
                );
                let tree = JsValue::Array(record_tree(Path::new(dir)));
                assert_eq!(
                    tree,
                    *field(operation, "targetTree"),
                    "{name} op #{index}: restore tree"
                );
            }
        }
        Err(error) => {
            assert!(
                expected.get("ok").is_none(),
                "{name} op #{index} ({op}): expected success, got {error}"
            );
            let value = error.as_json();
            let value = restore_dir
                .as_deref()
                .map_or(value.clone(), |dir| mask(&value, dir, "<restore>"));
            let value = mask(&value, &scratch.to_string_lossy(), "<dir>");
            let value = mask_restore_random(&value);
            assert_eq!(
                value,
                *field(expected, "error"),
                "{name} op #{index} ({op}): error mismatch"
            );
            // A failed restore can still leave a partially written tree (for
            // example, the first entry succeeds and a later entry is unsafe).
            // The recorder captures `targetTree` for both outcomes, so compare
            // it and the 0700 guarantee on the failure path too; otherwise an
            // implementation could leave extra files while returning the same
            // error.
            if let Some(dir) = &restore_dir {
                assert_eq!(
                    mode(dir),
                    0o700,
                    "{name} op #{index}: failed mkdtemp directory mode"
                );
                let tree = JsValue::Array(record_tree(Path::new(dir)));
                assert_eq!(
                    tree,
                    *field(operation, "targetTree"),
                    "{name} op #{index}: failed restore tree"
                );
            }
        }
    }
}

#[test]
fn fallback_and_empty_session_filter_cover_unreachable_entry_branches() {
    let scratch = Scratch::new();
    let root = scratch.0.join("snapshots");
    let manifest_dir = root.join("workspaces/w/sessions/s/snapshots/id");
    fs::create_dir_all(&manifest_dir).unwrap();
    fs::write(
        manifest_dir.join("manifest.json"),
        r#"{"snapshotId":"id","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","createdAt":"2026-01-01T00:00:00.000Z"}"#,
    )
    .unwrap();
    let provider = create_workspace_snapshot_provider(WorkspaceSnapshotConfig {
        root: root.to_string_lossy().into_owned(),
        snapshot_root: root.to_string_lossy().into_owned(),
    });
    let fallback = scratch.0.join("project").to_string_lossy().into_owned();
    let projection = SnapshotProjection::new(
        Some(provider),
        TestResolver {
            projects: vec![(fallback.clone(), "w".into())],
        },
        fallback.clone(),
    );

    // createLocalGateway.ts:1272 `input.projectKey ?? fallbackProjectRoot`.
    // The gateway entry rejects an omitted projectKey, so only the projection
    // unit can cover this branch.
    let listed = projection
        .list(&parse_json(r#"{"limit":10}"#).unwrap())
        .unwrap();
    assert_eq!(items(field(&listed, "items")).len(), 1);

    // createLocalGateway.ts:1280 `!input.sessionKey || ...`: an empty string
    // disables the filter here (the gateway entry rejects it earlier).
    let mut input = JsObject::new();
    input.insert("projectKey".into(), fallback.as_str().into());
    input.insert("sessionKey".into(), "".into());
    let listed = projection.list(&JsValue::Object(input)).unwrap();
    assert_eq!(items(field(&listed, "items")).len(), 1);
}

#[test]
fn capability_unavailable_precedes_project_resolution() {
    struct PanicResolver;
    impl SnapshotProjectResolver for PanicResolver {
        fn resolve_project_key(&self, _: &[u16]) -> Result<String, SnapshotProjectionError> {
            panic!("project resolution must not run when the provider is absent");
        }
        fn workspace_id(&self, _: &str) -> String {
            panic!("workspace resolution must not run when the provider is absent");
        }
    }
    let projection = SnapshotProjection::new(None, PanicResolver, "/fallback");
    let error = projection
        .list(&JsValue::Object(JsObject::new()))
        .expect_err("no provider");
    assert_eq!(error.name(), "DialogGatewayError");
    assert_eq!(error.code(), Some("CAPABILITY_UNAVAILABLE"));
    assert_eq!(
        error.message().to_utf8().unwrap(),
        "Gateway snapshot provider is unavailable."
    );
}

#[test]
fn snapshot_ids_keep_lone_surrogates_instead_of_matching_replacement() {
    let scratch = Scratch::new();
    let root = scratch.0.join("snapshots");
    let manifest_root = root.join("workspaces/w/sessions/s/snapshots");
    // `\ud800` and U+FFFD are distinct JS strings; the old lossy conversion
    // turned the first request into the second manifest's id.
    write_manifest(
        &manifest_root.join("a-surrogate"),
        br#"{"snapshotId":"\ud800","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","entries":[]}"#,
    );
    write_manifest(
        &manifest_root.join("z-replacement"),
        br#"{"snapshotId":"\ufffd","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","entries":[{"path":"../evil.txt","entryType":"file","objectKey":"objects/missing"}]}"#,
    );
    let provider = create_workspace_snapshot_provider(WorkspaceSnapshotConfig {
        root: root.to_string_lossy().into_owned(),
        snapshot_root: root.to_string_lossy().into_owned(),
    });
    let source = scratch.0.join("project");
    fs::create_dir_all(&source).unwrap();
    let target = scratch.0.join("target");
    fs::create_dir_all(&target).unwrap();
    let projection = SnapshotProjection::new(
        Some(provider),
        TestResolver {
            projects: vec![
                (source.to_string_lossy().into_owned(), "w".into()),
                (target.to_string_lossy().into_owned(), "target".into()),
            ],
        },
        source.to_string_lossy().into_owned(),
    );

    let surrogate = JsString::from_utf16(vec![0xD800]);
    let mut get = JsObject::new();
    get.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    get.insert("snapshotId".into(), JsValue::String(surrogate.clone()));
    let got = projection
        .get(&JsValue::Object(get))
        .expect("raw surrogate id resolves");
    assert_eq!(
        field(field(&got, "snapshot"), "snapshotId")
            .as_string()
            .expect("snapshot id")
            .units(),
        &[0xD800],
        "get must not replacement-decode the request"
    );

    let mut restore = JsObject::new();
    restore.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    restore.insert("snapshotId".into(), JsValue::String(surrogate));
    restore.insert(
        "targetProjectKey".into(),
        target.to_string_lossy().as_ref().into(),
    );
    projection
        .restore(&JsValue::Object(restore))
        .expect("restore resolves the surrogate manifest, not the replacement one");
    let dirs = restore_dirs(&target);
    assert_eq!(dirs.len(), 1, "one restore directory");
    assert!(
        record_tree(&target.join(&dirs[0])).is_empty(),
        "the surrogate manifest has no entries"
    );
}

#[test]
fn project_keys_keep_lone_surrogates_instead_of_matching_replacement_paths() {
    let scratch = Scratch::new();
    let root = scratch.0.join("snapshots");
    write_manifest(
        &root.join("workspaces/w/sessions/s/snapshots/id"),
        br#"{"snapshotId":"id","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","entries":[]}"#,
    );
    write_manifest(
        &root.join("workspaces/fffd/sessions/s/snapshots/replacement"),
        br#"{"snapshotId":"replacement","workspaceId":"fffd","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","entries":[]}"#,
    );
    let provider = create_workspace_snapshot_provider(WorkspaceSnapshotConfig {
        root: root.to_string_lossy().into_owned(),
        snapshot_root: root.to_string_lossy().into_owned(),
    });
    let source = scratch.0.join("project");
    // Literal U+FFFD is a legal filename on macOS and a distinct JS string
    // from the lone surrogate `"\ud800"`.
    let replacement = scratch.0.join("project-\u{FFFD}");
    let target_replacement = scratch.0.join("target-\u{FFFD}");
    for directory in [&source, &replacement, &target_replacement] {
        fs::create_dir_all(directory).unwrap();
    }
    let projection = SnapshotProjection::new(
        Some(provider),
        TestResolver {
            projects: vec![
                (source.to_string_lossy().into_owned(), "w".into()),
                (replacement.to_string_lossy().into_owned(), "fffd".into()),
                (
                    target_replacement.to_string_lossy().into_owned(),
                    "fffd-target".into(),
                ),
            ],
        },
        source.to_string_lossy().into_owned(),
    );

    let replacement_text = replacement.to_string_lossy().into_owned();
    // Same path with U+FFFD replaced by a lone surrogate: the lossy conversion
    // is byte-identical to the registered U+FFFD project, which is exactly the
    // cross-project alias this test forbids.
    let surrogate_key = with_lone_surrogate(scratch.0.join("project-").to_string_lossy().as_ref());
    assert_eq!(
        String::from_utf16_lossy(surrogate_key.units()),
        replacement_text,
        "the lossy view of the surrogate key aliases the U+FFFD project"
    );

    // Negative control: the surrogate key must not alias the literal U+FFFD
    // project (the old `from_utf16_lossy` compared both as U+FFFD), and the
    // rejection text keeps the original units.
    let mut list = JsObject::new();
    list.insert("projectKey".into(), JsValue::String(surrogate_key.clone()));
    let error = projection
        .list(&JsValue::Object(list))
        .expect_err("a surrogate projectKey is not the U+FFFD project");
    assert_eq!(error.code(), Some("PROJECT_NOT_FOUND"));
    assert_eq!(error.name(), "DialogGatewayError");
    let mut expected = "Unknown projectKey: ".encode_utf16().collect::<Vec<_>>();
    expected.extend(surrogate_key.units());
    assert_eq!(error.message().units(), expected.as_slice());
    assert_eq!(error.message().units().last(), Some(&0xD800));

    // Positive control: the literal U+FFFD project resolves and lists only its
    // own snapshot, so the two names remain distinct.
    let mut list = JsObject::new();
    list.insert("projectKey".into(), replacement_text.as_str().into());
    let listed = projection
        .list(&JsValue::Object(list))
        .expect("the literal U+FFFD project resolves");
    let rows = items(field(&listed, "items"));
    assert_eq!(rows.len(), 1);
    assert_eq!(text(field(&rows[0], "snapshotId")), "replacement");
    assert_eq!(text(field(&rows[0], "workspaceId")), "fffd");

    // Negative control on restore's targetProjectKey: a surrogate target must
    // be rejected before mkdtemp instead of creating a directory inside the
    // U+FFFD target project.
    let mut restore = JsObject::new();
    restore.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    restore.insert("snapshotId".into(), "id".into());
    restore.insert(
        "targetProjectKey".into(),
        JsValue::String(with_lone_surrogate(
            scratch.0.join("target-").to_string_lossy().as_ref(),
        )),
    );
    let error = projection
        .restore(&JsValue::Object(restore))
        .expect_err("a surrogate targetProjectKey is not the U+FFFD target");
    assert_eq!(error.code(), Some("PROJECT_NOT_FOUND"));
    assert_eq!(error.message().units().last(), Some(&0xD800));
    assert!(
        restore_dirs(&target_replacement).is_empty(),
        "no mkdtemp in the aliased target project"
    );

    // Positive control: the literal U+FFFD target restores normally.
    let mut restore = JsObject::new();
    restore.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    restore.insert("snapshotId".into(), "id".into());
    restore.insert(
        "targetProjectKey".into(),
        target_replacement.to_string_lossy().as_ref().into(),
    );
    projection
        .restore(&JsValue::Object(restore))
        .expect("the literal U+FFFD target restores");
    assert_eq!(restore_dirs(&target_replacement).len(), 1);
}

fn with_lone_surrogate(base: &str) -> JsString {
    let mut units = base.encode_utf16().collect::<Vec<_>>();
    units.push(0xD800);
    JsString::from_utf16(units)
}

#[test]
fn mkdtemp_normalizes_join_before_creating_the_directory() {
    let scratch = Scratch::new();
    let base = scratch.0.join("base");
    let tmp = base.join("tmp");
    let real = base.join("real");
    let real_sub = real.join("sub");
    fs::create_dir_all(&tmp).unwrap();
    fs::create_dir_all(&real_sub).unwrap();
    symlink(&real_sub, tmp.join("link")).unwrap();
    // Raw registry value: `link/..` is only `tmp` after Node's lexical join.
    // The OS instead follows the symlink, so a plain Path::join creates the
    // mkdtemp directory under `real`.
    let target_project = format!("{}/tmp/link/..", base.to_string_lossy());

    let root = scratch.0.join("snapshots");
    write_manifest(
        &root.join("workspaces/w/sessions/s/snapshots/id"),
        br#"{"snapshotId":"id","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","entries":[]}"#,
    );
    let provider = create_workspace_snapshot_provider(WorkspaceSnapshotConfig {
        root: root.to_string_lossy().into_owned(),
        snapshot_root: root.to_string_lossy().into_owned(),
    });
    let source = scratch.0.join("project");
    fs::create_dir_all(&source).unwrap();
    let projection = SnapshotProjection::new(
        Some(provider),
        TestResolver {
            projects: vec![
                (source.to_string_lossy().into_owned(), "w".into()),
                (target_project.clone(), "target".into()),
            ],
        },
        source.to_string_lossy().into_owned(),
    );
    let mut input = JsObject::new();
    input.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    input.insert("snapshotId".into(), "id".into());
    input.insert("targetProjectKey".into(), target_project.as_str().into());
    let restored = projection
        .restore(&JsValue::Object(input))
        .expect("restore into the normalized target");
    let workspace_key = text(field(&restored, "workspaceKey"));
    assert!(
        workspace_key.starts_with(&format!(
            "{}/tmp/.pilotdeck-restore-",
            base.to_string_lossy()
        )),
        "workspaceKey is the normalized directory: {workspace_key}"
    );
    assert_eq!(
        restore_dirs(&tmp).len(),
        1,
        "mkdtemp lands where path.join points"
    );
    assert!(
        restore_dirs(&real).is_empty(),
        "the symlink-resolved parent must not receive a stray directory"
    );
    assert_eq!(mode(tmp.join(&restore_dirs(&tmp)[0])), 0o700);
}

#[test]
fn host_required_collation_keeps_the_host_boundary_marker() {
    let scratch = Scratch::new();
    let root = scratch.0.join("snapshots");
    let manifest_root = root.join("workspaces/w/sessions/s/snapshots");
    write_manifest(
        &manifest_root.join("a-surrogate"),
        br#"{"snapshotId":"a","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","createdAt":"\ud800","entries":[]}"#,
    );
    write_manifest(
        &manifest_root.join("b-replacement"),
        br#"{"snapshotId":"b","workspaceId":"w","sessionId":"s","turnId":"t","runId":"r","phase":"pre_user","createdAt":"\ufffd","entries":[]}"#,
    );
    let provider = create_workspace_snapshot_provider(WorkspaceSnapshotConfig {
        root: root.to_string_lossy().into_owned(),
        snapshot_root: root.to_string_lossy().into_owned(),
    });
    let source = scratch.0.join("project");
    fs::create_dir_all(&source).unwrap();
    let projection = SnapshotProjection::new(
        Some(provider),
        TestResolver {
            projects: vec![(source.to_string_lossy().into_owned(), "w".into())],
        },
        source.to_string_lossy().into_owned(),
    );
    let mut input = JsObject::new();
    input.insert(
        "projectKey".into(),
        source.to_string_lossy().as_ref().into(),
    );
    let error = projection
        .list(&JsValue::Object(input))
        .expect_err("unpaired-surrogate collation is a host boundary");
    assert_eq!(error.code(), Some("JS_HOST_REQUIRED"));
    assert!(error.requires_host(), "A8 must be able to forward it");
    assert_eq!(error.name(), "Error");
}

fn write_manifest(directory: &Path, bytes: &[u8]) {
    fs::create_dir_all(directory).unwrap();
    fs::write(directory.join("manifest.json"), bytes).unwrap();
}

fn mode(path: impl AsRef<Path>) -> u32 {
    fs::metadata(path).unwrap().permissions().mode() & 0o777
}
