//! Snapshot management projection replay. The oracle is produced by the real TS
//! `createLocalGateway` (see tests/fixtures/snapshot-projection/README.md):
//! real recorder snapshots, real list/get/restore calls, and the exact restore
//! trees. This test materializes the recorded snapshot root, replays every
//! operation against `runtime::snapshot::SnapshotProjection`, and compares
//! values and errors item by item.
//!
//! Counts are pinned: an empty or shrunk `scenarios` array fails instead of
//! passing with zero iterations (same class as #293's zero-scenario P2).
#[path = "common/baseline.rs"]
