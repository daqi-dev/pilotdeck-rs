//! Production A7 inbound port: the channel hands a turn to the same
//! `TurnSubmitter` the WS host owns. No session owner, admission or projection
//! state is created here.
use super::protocol::*;
use crate::{
    metadata::object,
    runtime::turn::submit::{TurnSubmission, TurnSubmitter},
};
use pilotdeck_protocol::JsValue;
use std::sync::Arc;

pub struct SubmitterTurnGateway {
    submitter: Arc<TurnSubmitter>,
    channel_key: ChannelKey,
}

impl SubmitterTurnGateway {
    /// Only the `channelKey` is adapter-specific; the submitter is shared.
    pub fn new(submitter: Arc<TurnSubmitter>, channel_key: ChannelKey) -> Self {
        Self {
            submitter,
            channel_key,
        }
    }

    pub fn api_server(submitter: Arc<TurnSubmitter>) -> Self {
        Self::new(submitter, ChannelKey::new("api_server"))
    }
}

impl TurnGateway for SubmitterTurnGateway {
    fn submit(
        &self,
        request: TurnRequest,
    ) -> BoxFuture<Result<Box<dyn TurnEventStream>, ChannelError>> {
        // The TS api-server passes exactly these three fields; absent runId is
        // generated by the acceptor, as in InProcessGateway.submitTurn.
        let input = object([
            ("sessionKey", JsValue::String(request.session_key)),
            (
                "channelKey",
                JsValue::String(self.channel_key.as_js().clone()),
            ),
            ("message", JsValue::String(request.message)),
        ]);
        let submission = self.submitter.submit(input);
        Box::pin(
            async move { Ok(Box::new(SubmissionStream(submission)) as Box<dyn TurnEventStream>) },
        )
    }
}

struct SubmissionStream(TurnSubmission);

impl TurnEventStream for SubmissionStream {
    fn next(
        &mut self,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<Option<JsValue>, ChannelError>> + Send + '_>,
    > {
        Box::pin(async move {
            self.0
                .next()
                .await
                .map_err(|error| ChannelError::Error(error.message))
        })
    }
}
