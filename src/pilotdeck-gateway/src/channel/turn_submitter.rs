//! Production A7 inbound port: the channel hands a turn to the same
//! `TurnSubmitter` the WS host owns. No session owner, admission or projection
//! state is created here.
use super::protocol::*;
use crate::{
    metadata::object,
    runtime::turn::submit::{TurnSubmission, TurnSubmitter},
};
use pilotdeck_protocol::JsValue;
use std::sync::Arc;

pub struct SubmitterTurnGateway {
    submitter: Arc<TurnSubmitter>,
}

impl SubmitterTurnGateway {
    /// The submitter is shared; the channel identity travels on each request
    /// (`TurnRequest.channel_key`), like the TS adapters' `submitTurn`
    /// `channelKey` field — the gateway never stamps one of its own.
    pub fn new(submitter: Arc<TurnSubmitter>) -> Self {
        Self { submitter }
    }
}

impl TurnGateway for SubmitterTurnGateway {
    fn submit(
        &self,
        request: TurnRequest,
    ) -> BoxFuture<Result<Box<dyn TurnEventStream>, ChannelError>> {
        self.submit_with_options(request, ChannelTurnOptions::default())
    }

    fn submit_with_options(
        &self,
        request: TurnRequest,
        options: ChannelTurnOptions,
    ) -> BoxFuture<Result<Box<dyn TurnEventStream>, ChannelError>> {
        // The TS adapters pass exactly these three fields (the api-server's
        // `channelKey: "api_server"`, ApiServerChannel.ts:319/:376); absent
        // runId is generated by the acceptor, as in InProcessGateway.submitTurn.
        // #2301 fix-r1: the requester's key, never a construction-time one —
        // the shared assembly gateway used to overwrite it with the first
        // consumer's identity, so an apiServer turn entered A7 as `feishu`.
        let mut input = object([
            ("sessionKey", JsValue::String(request.session_key)),
            (
                "channelKey",
                JsValue::String(request.channel_key.as_js().clone()),
            ),
            ("message", JsValue::String(request.message)),
        ]);
        let JsValue::Object(ref mut object) = input else {
            unreachable!("channel input object")
        };
        if let Some(project) = options.project_key {
            object.insert("projectKey".into(), JsValue::String(project));
        }
        if !options.attachments.is_empty() {
            object.insert("attachments".into(), JsValue::Array(options.attachments));
        }
        if let Some(allowed) = options.allow_plan_mode_tools {
            object.insert("allowPlanModeTools".into(), JsValue::Bool(allowed));
        }
        if let Some(mode) = options.mode {
            object.insert("mode".into(), JsValue::String(mode));
        }
        if let Some(mode) = options.base_permission_mode {
            object.insert("basePermissionMode".into(), JsValue::String(mode));
        }
        if let Some(timeout) = options.timeout_ms {
            object.insert("timeoutMs".into(), JsValue::Number(timeout));
        }
        if !options.synthetic_messages.is_empty() {
            object.insert(
                "syntheticMessages".into(),
                JsValue::Array(options.synthetic_messages),
            );
        }
        let submission = self.submitter.submit(input);
        Box::pin(
            async move { Ok(Box::new(SubmissionStream(submission)) as Box<dyn TurnEventStream>) },
        )
    }
}

struct SubmissionStream(TurnSubmission);

impl TurnEventStream for SubmissionStream {
    fn next(
        &mut self,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<Option<JsValue>, ChannelError>> + Send + '_>,
    > {
        Box::pin(async move {
            self.0
                .next()
                .await
                .map_err(|error| ChannelError::Error(error.message))
        })
    }
}
